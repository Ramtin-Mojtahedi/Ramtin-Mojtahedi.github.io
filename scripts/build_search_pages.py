def truncate(value: str, limit: int = 158) -> str:
    if len(value) <= limit:
        return value
    shortened = value[: limit - 1].rsplit(" ", 1)[0].rstrip(" ,;:-")
    return shortened + "…"


def description_for(
    title: str,
    *,
    has_doi: bool,
    abstract: str = "",
    venue: str = "",
    year: int | None = None,
) -> str:
    if abstract:
        return truncate(plain_text(abstract), 155)
    year_text = str(year) if year else "undated"
    detail = "citation, DOI, and access links" if has_doi else "citation and access links"
    full = f"{title} — {venue} ({year_text}). Verified {detail}." if venue else ""
    if full and len(full) <= 155:
        return full
    suffix = f" — {year_text}. Verified {detail}."
    available = 155 - len(suffix)
    if len(title) > available:
        short_title = title[: max(1, available - 1)].rsplit(" ", 1)[0].rstrip(" ,.;:-—") + "…"
    else:
        short_title = title
    return truncate(short_title + suffix, 155)


