def publications_index(publications: list[dict[str, object]]) -> str:
    cards: list[str] = []
    item_list: list[dict[str, object]] = []
    for position, publication in enumerate(publications, start=1):
        canonical = publication_url(publication)
        authors = ", ".join(author_names(publication))
        citation = plain_text(publication.get("citation_plain") or publication.get("citation", ""))
        keywords = [plain_text(value) for value in publication.get("keywords", []) if plain_text(value)]
        work_type = publication_type_label(publication)
        access_value = "public" if public_full_text_url(publication) else "metadata"
        repository_value = "linked" if publication.get("code_url") else "none"
        search_text = " ".join(
            [str(publication.get("title") or ""), authors, citation, work_type, *keywords]
        ).casefold()
        badges = [str(publication.get("year")), str(publication.get("status") or "")]
        if publication.get("open_access_url") or publication.get("citation_pdf_url"):
            badges.append("Public full text")
        if publication.get("preprint_url"):
            badges.append("Preprint")
        if publication.get("code_url"):
            badges.append("Code")
        topics = (
            '<ul class="paper-topics" role="list">'
            + "".join(f"<li>{esc(keyword)}</li>" for keyword in keywords)
            + "</ul>"
            if keywords
            else ""
        )
        cards.append(
            f'''<li class="paper" data-publication-card data-year="{esc(publication.get('year'), attribute=True)}" data-type="{esc(str(publication.get('type') or ''), attribute=True)}" data-access="{access_value}" data-repository="{repository_value}" data-search="{esc(search_text, attribute=True)}">
  <div class="paper-meta">{"".join(f"<span>{esc(badge)}</span>" for badge in badges if badge)}</div>
  <h2><a href="/publications/{esc(publication['id'], attribute=True)}/">{esc(publication['title'])}</a></h2>
  <p class="authors">{esc(authors)}</p>
  <p>{esc(citation)}</p>
  {topics}
  <p class="paper-record-link"><a href="/publications/{esc(publication['id'], attribute=True)}/">Open the verified record <span aria-hidden="true">→</span></a></p>
</li>'''
        )
        item_list.append(
            {
                "@type": "ListItem",
                "position": position,
                "url": canonical,
                "name": str(publication["title"]),
            }
        )

    years = sorted({int(publication["year"]) for publication in publications}, reverse=True)
    publication_types = sorted(
        {str(publication.get("type") or "") for publication in publications},
        key=lambda value: TYPE_LABELS.get(value, value),
    )
