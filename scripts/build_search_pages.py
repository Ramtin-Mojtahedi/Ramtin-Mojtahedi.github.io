def citation_container(publication: dict[str, object]) -> dict[str, object] | None:
    venue = str(publication.get("venue") or "").strip()
    volume = str(publication.get("volume") or "").strip()
    publication_type = str(publication.get("type") or "")
    if not venue:
        return None
    if publication_type == "journal-article":
        periodical: dict[str, object] = {"@type": "Periodical", "name": venue}
        if volume:
            return {
                "@type": "PublicationVolume",
                "volumeNumber": volume,
                "isPartOf": periodical,
            }
        return periodical
    if volume:
        return {
            "@type": "PublicationVolume",
            "volumeNumber": volume,
            "isPartOf": {"@type": "CreativeWork", "name": venue},
        }
    return {"@type": "CreativeWork", "name": venue}


def citation_meta(publication: dict[str, object]) -> str:
    publication_type = str(publication.get("type") or "")
    venue = str(publication.get("venue") or "").strip()
    volume = str(publication.get("volume") or "").strip()
    issue = str(publication.get("issue") or "").strip()
    pages = str(publication.get("pages") or "").strip()
    article_number = str(publication.get("article_number") or "").strip()
    doi = str(publication.get("doi") or "").strip()
    citation_pdf_url = str(publication.get("citation_pdf_url") or "").strip()
    publisher = str(publication.get("publisher") or "").strip()
    keywords = publication.get("keywords") if isinstance(publication.get("keywords"), list) else []
    lines = [
        f'  <meta name="citation_author" content="{esc(name, attribute=True)}">'
        for name in citation_author_names(publication)
    ]
    lines.append('  <meta name="citation_language" content="en">')
    if venue:
        if publication_type == "journal-article":
            field = "citation_journal_title"
        elif publication_type == "dissertation":
            field = "citation_dissertation_institution"
        else:
            field = "citation_conference_title"
        lines.append(f'  <meta name="{field}" content="{esc(venue, attribute=True)}">')
    if volume:
        lines.append(f'  <meta name="citation_volume" content="{esc(volume, attribute=True)}">')
    if issue:
        lines.append(f'  <meta name="citation_issue" content="{esc(issue, attribute=True)}">')
    if pages:
        page_parts = re.split(r"\s*[-–—]\s*", pages, maxsplit=1)
        lines.append(f'  <meta name="citation_firstpage" content="{esc(page_parts[0], attribute=True)}">')
        if len(page_parts) == 2:
            lines.append(f'  <meta name="citation_lastpage" content="{esc(page_parts[1], attribute=True)}">')
    elif article_number:
        lines.append(f'  <meta name="citation_firstpage" content="{esc(article_number, attribute=True)}">')
    if doi:
        lines.append(f'  <meta name="citation_doi" content="{esc(doi, attribute=True)}">')
    if publisher:
        lines.append(f'  <meta name="citation_publisher" content="{esc(publisher, attribute=True)}">')
    if keywords:
        lines.append(
            f'  <meta name="citation_keywords" content="{esc("; ".join(str(value) for value in keywords), attribute=True)}">'
        )
    if citation_pdf_url:
        lines.append(
            f'  <meta name="citation_pdf_url" content="{esc(citation_pdf_url, attribute=True)}">'
        )
    return "\n".join(lines)


def bibtex_key(publication: dict[str, object]) -> str:
    explicit = str(publication.get("bibtex_key") or "").strip()
    if explicit:
        return explicit
    words = re.findall(r"[A-Za-z0-9]+", plain_text(publication.get("title")))[:4]
    title_key = "".join(word[:1].upper() + word[1:] for word in words)
    return f"Mojtahedi{publication.get('year')}{title_key or publication.get('id')}"


def bibtex_type(publication: dict[str, object]) -> str:
    explicit = str(publication.get("bibtex_type") or "").strip().lower()
    if explicit:
        return explicit
    return {
        "journal-article": "article",
        "conference-paper": "inproceedings",
        "dissertation": "phdthesis",
    }.get(str(publication.get("type") or ""), "misc")


def bibtex_text(value: object) -> str:
    text = plain_text(value)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(character, character) for character in text)


def bibtex_entry(publication: dict[str, object]) -> str:
    entry_type = bibtex_type(publication)
    fields: list[tuple[str, object]] = [
        ("author", " and ".join(author_names(publication))),
        ("title", publication.get("title")),
        ("year", publication.get("year")),
    ]
    if entry_type == "article":
        fields.extend(
            [
                ("journal", publication.get("venue")),
                ("volume", publication.get("volume")),
                ("number", publication.get("issue")),
                ("pages", publication.get("pages")),
                ("eid", publication.get("article_number")),
            ]
        )
    elif entry_type == "inproceedings":
        fields.extend(
            [
                ("booktitle", publication.get("venue")),
                ("volume", publication.get("volume")),
                ("pages", publication.get("pages")),
                ("publisher", publication.get("publisher")),
            ]
        )
    elif entry_type == "phdthesis":
        fields.extend(
            [
                ("school", publication.get("venue") or publication.get("publisher")),
                ("type", "Doctoral dissertation"),
            ]
        )
    else:
        fields.append(("howpublished", publication.get("venue")))
    fields.extend(
        [
            ("doi", publication.get("doi")),
            ("url", publication.get("url") or publication_url(publication)),
            ("note", publication.get("note")),
        ]
    )
    rendered_fields = []
    for name, value in fields:
        if not str(value or "").strip():
            continue
        escaped = bibtex_text(value)
        if name == "title":
            escaped = "{" + escaped + "}"
        rendered_fields.append(f"  {name} = {{{escaped}}}")
    body = ",\n".join(rendered_fields)
    return f"@{entry_type}{{{bibtex_key(publication)},\n{body}\n}}"


def ris_entry(publication: dict[str, object]) -> str:
    ris_type = {
        "journal-article": "JOUR",
        "conference-paper": "CPAPER",
        "conference-abstract": "CPAPER",
        "conference-presentation": "CONF",
        "dissertation": "THES",
    }.get(str(publication.get("type") or ""), "GEN")
    lines = [f"TY  - {ris_type}", f"TI  - {plain_text(publication.get('title'))}"]
    lines.extend(f"AU  - {name}" for name in author_names(publication))
    lines.append(f"PY  - {publication.get('year')}")
    publication_date = str(publication.get("publication_date") or "").strip()
    if publication_date:
        lines.append(f"DA  - {publication_date}")
    venue = plain_text(publication.get("venue"))
    if venue:
        lines.append(f"T2  - {venue}")
    if publication.get("volume"):
        lines.append(f"VL  - {plain_text(publication.get('volume'))}")
    if publication.get("issue"):
        lines.append(f"IS  - {plain_text(publication.get('issue'))}")
    pages = str(publication.get("pages") or "").strip()
    if pages:
        page_parts = re.split(r"\s*[-–—]\s*", pages, maxsplit=1)
        lines.append(f"SP  - {page_parts[0]}")
        if len(page_parts) == 2:
            lines.append(f"EP  - {page_parts[1]}")
    elif publication.get("article_number"):
        lines.append(f"SP  - {plain_text(publication.get('article_number'))}")
    if publication.get("doi"):
        lines.append(f"DO  - {plain_text(publication.get('doi'))}")
    lines.append(f"UR  - {publication.get('url') or publication_url(publication)}")
    lines.extend(
        f"KW  - {plain_text(keyword)}"
        for keyword in publication.get("keywords", [])
        if plain_text(keyword)
    )
    if publication.get("note"):
        lines.append(f"N1  - {plain_text(publication.get('note'))}")
    lines.append("ER  -")
    return "\n".join(lines) + "\n"

def publication_type_label(publication: dict[str, object]) -> str:
    publication_type = str(publication.get("type") or "")
    return TYPE_LABELS.get(publication_type, publication_type.replace("-", " ").title() or "Scholarly work")

def public_full_text_url(publication: dict[str, object]) -> str:
    return str(
        publication.get("citation_pdf_url")
        or publication.get("open_access_url")
        or publication.get("preprint_url")
        or publication.get("pmc_url")
        or ""
    ).strip()

def external_record_labels(publication: dict[str, object]) -> list[str]:
    labels: list[str] = []
    if publication.get("doi"):
        labels.append("DOI")
    elif publication.get("url"):
        source_label = re.sub(
            r"\s*[↗→]+\s*$", "", plain_text(publication.get("link_label") or "")
        ).strip()
        labels.append(source_label or "Source record")
    if publication.get("pubmed_url"):
        labels.append("PubMed")
    if publication.get("pmc_url"):
        labels.append("PMC")
    if publication.get("preprint_url"):
        labels.append("arXiv/preprint")
    if publication.get("institutional_url"):
        labels.append("Institution record")
    if publication.get("bibliography_url"):
        labels.append("Bibliography record")
    return labels

def record_overview(publication: dict[str, object]) -> str:
    publication_type = str(publication.get("type") or "")
    work_type = publication_type_label(publication).lower()
    year = int(publication["year"])
    venue = str(publication.get("venue") or "").strip()
    if publication_type == "conference-presentation":
        opening = f"This record documents a conference presentation at {venue} ({year})."
    elif publication_type == "conference-abstract":
        opening = f"This conference abstract is recorded in {venue} ({year})."
    elif publication_type == "dissertation":
        opening = f"This author-supplied record describes a doctoral dissertation associated with {venue} ({year})."
    elif venue:
        opening = f"This {work_type} is recorded in {venue} ({year})."
    else:
        opening = f"This {work_type} is catalogued for {year}."
    has_external_record = bool(publication.get("url") or external_record_labels(publication))
    has_artifact = bool(public_full_text_url(publication) or publication.get("code_url"))
    if has_external_record or has_artifact:
        closing = "This page consolidates verified bibliographic metadata and the external records or research artifacts listed here."
    else:
        closing = "No authoritative external record, public full text, or research repository has yet been verified for this entry."
    return f"{opening} {closing}"

