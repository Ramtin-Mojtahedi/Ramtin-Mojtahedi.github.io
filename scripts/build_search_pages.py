def research_groups(
    publications: list[dict[str, object]],
) -> list[tuple[str, str, list[dict[str, object]]]]:
    clinical_terms = {
        "radiomic", "radiomics", "risk", "response", "therapy", "chemotherapy",
        "clinical", "multimodal", "cardiovascular", "slice thickness", "pancreatic",
        "survival prediction",
    }
    clinical: list[dict[str, object]] = []
    imaging: list[dict[str, object]] = []
    engineering: list[dict[str, object]] = []
    for publication in publications:
        searchable = " ".join(
            [
                str(publication.get("title") or ""),
                *(str(value) for value in publication.get("keywords") or []),
            ]
        ).casefold()
        if int(publication["year"]) <= 2017:
            engineering.append(publication)
        elif any(term in searchable for term in clinical_terms):
            clinical.append(publication)
        else:
            imaging.append(publication)
    return [
        (
            "Medical image segmentation and data-efficient learning",
            "Work on tumour segmentation and classification using vision transformers, self-supervised and contrastive learning, few-shot learning, persistent homology, and parameter-efficient adaptation of foundation models.",
            imaging,
        ),
        (
            "Multimodal clinical prediction and radiomics",
            "Research records connecting CT imaging, radiomic features, clinical variables, and machine-learning models for risk stratification, treatment response, and outcome prediction.",
            clinical,
        ),
        (
            "Engineering foundations",
            "Earlier work in signal processing, FPGA-based tracking, image encryption, Bayesian filtering, and sensor systems that forms part of the broader technical record.",
            engineering,
        ),
    ]


