def esc(value: object, *, attribute: bool = False) -> str:
    return html.escape(str(value or ""), quote=attribute)


def plain_text(value: object) -> str:
    text = str(value or "")
    text = re.sub(r"<sup\b[^>]*>.*?</sup>", "", text, flags=re.IGNORECASE | re.DOTALL)
    text = re.sub(r"<[^>]+>", "", text)
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


def author_names(publication: dict[str, object]) -> list[str]:
    names = publication.get("authors")
    if isinstance(names, list) and all(isinstance(name, str) and name.strip() for name in names):
        return [name.strip() for name in names]
    text = plain_text(publication.get("authors_html", "")).rstrip(".")
    text = re.sub(r",?\s+and\s+", ", ", text, flags=re.IGNORECASE)
    return [part.strip().rstrip(".") for part in text.split(",") if part.strip()]


def citation_author_names(publication: dict[str, object]) -> list[str]:
    names = publication.get("citation_authors")
    if isinstance(names, list) and all(isinstance(name, str) and name.strip() for name in names):
        return [name.strip() for name in names]
    return author_names(publication)


def formatted_citation(publication: dict[str, object]) -> str:
    names = author_names(publication)
    if len(names) > 2:
        authors = ", ".join(names[:-1]) + ", and " + names[-1]
    elif len(names) == 2:
        authors = " and ".join(names)
    else:
        authors = names[0] if names else ""
    title = plain_text(publication.get("title"))
    source = plain_text(publication.get("citation_plain") or publication.get("citation")).rstrip(".")
    parts = [f"{authors}." if authors else "", f'“{title}.”' if title else "", f"{source}." if source else ""]
    doi = str(publication.get("doi") or "").strip()
    source_url = str(publication.get("url") or "").strip()
    if doi:
        parts.append(f"https://doi.org/{doi}")
    elif source_url:
        parts.append(source_url)
    return " ".join(part for part in parts if part)



