def related_publications(
    publication: dict[str, object], publications: list[dict[str, object]], *, limit: int = 3
) -> list[dict[str, object]]:
    current_keywords = {str(value).casefold() for value in publication.get("keywords") or []}
    current_group = str(publication.get("group") or "").casefold()
    current_year = int(publication["year"])
    ranked: list[tuple[int, int, str, dict[str, object]]] = []
    for candidate in publications:
        if candidate["id"] == publication["id"]:
            continue
        candidate_keywords = {str(value).casefold() for value in candidate.get("keywords") or []}
        overlap = len(current_keywords & candidate_keywords)
        same_group = bool(current_group and current_group == str(candidate.get("group") or "").casefold())
        score = overlap * 10 + (4 if same_group else 0)
        if score:
            ranked.append(
                (score, -abs(current_year - int(candidate["year"])), str(candidate["title"]), candidate)
            )
    ranked.sort(key=lambda item: (-item[0], -item[1], item[2].casefold()))
    return [item[3] for item in ranked[:limit]]


